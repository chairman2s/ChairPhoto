//! Resumable background sharpness-indexing job (H16b).
//!
//! [`run_index`] is the single entry point. It:
//!
//! 1. Queries all photos where `sharpness IS NULL` (unscored) or whose score carries no
//!    [`SHARPNESS_BASIS`] stamp (a score from before #245, see below).
//! 2. Resolves each photo to its cached ~2048px preview path via the catalog resolver.
//! 3. Loads the preview bytes with the thumbnail pipeline (`preview_bytes`), which ensures
//!    the preview is at 1024–2048px — the minimum resolution needed to see micro-blur.
//!    **Never uses the 256px thumbnail**: micro-blur is invisible there (see design doc).
//! 4. Decodes the JPEG, scores it with [`crate::sharpness::score_image`] (`method='tile'`).
//! 5. Writes `(sharpness, sharpness_method)` back to the catalog via
//!    `Catalog::set_sharpness`.
//! 6. Emits `sharpness:progress {done, total}` events after each processed photo.
//! 7. Checks the `abort` flag after each photo — stops cleanly when tripped, leaving
//!    unscored rows for the next run (resume-safe because `sharpness IS NULL` is the queue).
//!
//! ## The Preview, Not the Thumbnail
//!
//! The 256px thumbnail cannot show micro-blur: a back-focused eye looks sharp at that size.
//! We score on the ~1024–2048px cached preview. The preview is generated by the same decode
//! pipeline as the loupe (`thumbnails::preview_bytes`), cached on disk keyed by path+mtime,
//! so a subsequent loupe open is a free cache hit.
//!
//! ## Parallelism
//!
//! Preview loading + decode + scoring is CPU+I/O bound. We use rayon for the parallel decode
//! pass, the same pattern as `plugins/faces/indexer.rs` — resolve + load + score in parallel,
//! then collect results back to a sequential loop for SQLite writes (which require `&Connection`,
//! not `Send`).
//!
//! ## Resume-safety
//!
//! The indexer's "queue" is implicit: `SELECT id FROM photos WHERE sharpness IS NULL`. Writing
//! the score atomically to `photos` (one UPDATE per photo) means a crash mid-run leaves the
//! remaining rows as IS NULL → the next run picks them up automatically. No separate queue table.
//!
//! ## Score-on-import path
//!
//! Newly imported photos are scored for free via the I7b analyzer hook in
//! `thumbnails::register_analyzer`. The hook receives the freshly decoded image from the
//! thumbnail/preview/warm-all pipeline and calls [`settle_from_decode`], so scoring rides the
//! existing decode instead of re-reading the file. [`run_index`] is the batch backfill; since
//! the Tauri shell's `index_sharpness` command went (#165) nothing in the GPUI app starts it,
//! so the hook is the only writer that runs today.
//!
//! ## Scores from before #245
//!
//! Before #245 the preview tier enlarged a decode smaller than 2048 px to 2048 px, and the
//! batch indexer scored that enlarged preview: interpolated pixels, a lower Laplacian
//! variance than the photo's own. Every score written since carries
//! `photos.sharpness_basis = `[`SHARPNESS_BASIS`]. A score without it (`NULL`) is *legacy*:
//! written before the stamp existed, or by an older build, by a path that is not recorded.
//! Whether it is stale depends on the size of the decode it came from, which the catalog does
//! not hold (for a RAW it is the embedded preview's size, not the sensor's), so it is decided
//! the next time that decode is in hand ([`legacy_score_is_stale`]): a decode under 2048 px
//! was enlarged then, and the photo is scored again; one of 2048 px or more was only ever
//! shrunk, and its score is kept and stamped. Either way the old score stays in place until
//! that moment, so no culling signal goes blank while it waits.

use std::path::Path;
use std::sync::atomic::{AtomicBool, Ordering};

use rusqlite::Connection;
use serde::Serialize;

/// The `sharpness_method` value written by the tiled scorer (H16b). The region-aware
/// methods (`face` / `afpoint`, H16c) come from [`crate::sharpness_regions::Method`].
pub const METHOD_TILE: &str = "tile";

/// `photos.sharpness_basis` of every score written since #245: measured on a decode at its
/// own size, never on one enlarged to the preview tier. `NULL` beside a score marks a legacy
/// score (see the module doc). Raise it, and teach [`legacy_score_is_stale`] the old values,
/// if what a score is measured on changes again.
pub const SHARPNESS_BASIS: i64 = 1;

/// Whether a legacy score (no [`SHARPNESS_BASIS`]) must be measured again, given the pixel
/// size of the photo's preview-tier decode now. Under 2048 px on the long edge, the pre-#245
/// preview enlarged it, so the score was measured on interpolated pixels; at 2048 px or more
/// that preview was a plain downscale, as it is today, and the score stands.
pub fn legacy_score_is_stale(width: u32, height: u32) -> bool {
    width.max(height) < crate::thumbnails::PREVIEW_MAX
}

/// Progress event payload for `sharpness:progress`.
#[derive(Debug, Clone, Serialize)]
pub struct SharpnessProgress {
    pub done: usize,
    pub total: usize,
}

/// How an index run ended.
#[derive(Debug, Clone, Default, Serialize)]
pub struct IndexOutcome {
    /// Photos actually scored in this run (legacy scores measured again included).
    pub done: usize,
    /// Legacy scores kept as they were and stamped, because their preview was never enlarged.
    pub kept: usize,
    /// Photos that were unscored, or held a legacy score, when the run started (the queue).
    pub total: usize,
    /// Photos whose preview could not be generated (unreadable/undecodable file).
    pub failed: usize,
    /// Photos skipped because no reachable copy exists right now (offline/NAS).
    pub offline: usize,
    /// True when the run stopped early because the abort flag tripped.
    pub aborted: bool,
}

/// Run the sharpness-indexing job.
///
/// - `conn`            — a *secondary* catalog connection (no lock contention with the UI).
/// - `resolve_path_fn` — closure that, given a photo_id, returns `Ok(Some(path))` when a
///                       reachable copy is found, `Ok(None)` when offline, `Err` on failure.
///                       In production this calls `catalog.resolve_photo_path(id)`.
/// - `regions_fn`      — closure that, given a photo_id, returns its [`RegionInputs`] (face
///                       boxes + AF point) read from the catalog. Called **sequentially**
///                       (the connection is not `Sync`), so it may touch the DB freely.
///                       Returns `RegionInputs::default()` (→ tile method) when nothing is
///                       available.
/// - `preview_fn`      — closure that, given `&Path`, returns JPEG bytes at ~1024–2048px.
///                       In production this calls `thumbnails::preview_bytes`.
/// - `score_fn`        — closure that, given raw JPEG bytes and the photo's [`RegionInputs`],
///                       returns the sharpness score **and the method** used
///                       (`tile` / `face` / `afpoint`). It applies the region-aware priority
///                       chain (H16c): score inside face boxes when present, else at the AF
///                       point, else tiles. In production this is [`score_jpeg_regions`].
///                       Must be `Send + Sync` because it is called from rayon worker threads.
/// - `abort`           — shared abort flag; checked after each batch.
/// - `emit_progress`   — callback receiving `SharpnessProgress` after each processed photo.
///
/// Returns an `IndexOutcome`.
pub fn run_index<ResolveFn, RegionsFn, PreviewFn, ScoreFn, EmitFn>(
    conn: &Connection,
    resolve_path_fn: ResolveFn,
    regions_fn: RegionsFn,
    preview_fn: &PreviewFn,
    score_fn: &ScoreFn,
    abort: &AtomicBool,
    mut emit_progress: EmitFn,
) -> Result<IndexOutcome, String>
where
    ResolveFn: Fn(i64) -> Result<Option<std::path::PathBuf>, String>,
    RegionsFn: Fn(i64) -> RegionInputs,
    PreviewFn: Fn(&Path) -> Result<Vec<u8>, String> + Sync,
    ScoreFn: Fn(&[u8], &RegionInputs) -> Option<(f64, &'static str)> + Sync,
    EmitFn: FnMut(SharpnessProgress),
{
    use rayon::prelude::*;

    // Collect all unscored and legacy photo ids. This is the implicit queue.
    let queue = load_queue(conn)?;
    let total = queue.len();
    let mut outcome = IndexOutcome { total, ..IndexOutcome::default() };
    let mut done = 0usize;

    // Process in chunks so each chunk's results are written before the next starts,
    // keeping memory bounded and giving the abort flag a chance to trip at each boundary.
    const CHUNK: usize = 64;
    for chunk in queue.chunks(CHUNK) {
        if abort.load(Ordering::Relaxed) {
            outcome.aborted = true;
            break;
        }

        // ── Step 1: sequential resolve + region-gather pass ──────────────────────
        // Collect (photo_id, path, regions) for photos that are currently reachable. The
        // region inputs (face boxes / AF point) are read from the catalog *here*, in the
        // sequential pass, because the rusqlite `Connection` is not `Sync` and cannot be
        // touched from the parallel scoring workers below.
        let mut to_score: Vec<(i64, bool, std::path::PathBuf, RegionInputs)> =
            Vec::with_capacity(chunk.len());
        for &(photo_id, legacy) in chunk {
            match resolve_path_fn(photo_id) {
                Ok(Some(p)) => {
                    let regions = regions_fn(photo_id);
                    to_score.push((photo_id, legacy, p, regions));
                }
                Ok(None) => {
                    // Photo is offline; leave unscored for next run.
                    eprintln!(
                        "sharpness_index: photo {photo_id} is offline — skipping for this run"
                    );
                    outcome.offline += 1;
                }
                Err(e) => {
                    eprintln!("sharpness_index: resolve failed for photo {photo_id}: {e}");
                    outcome.offline += 1;
                }
            }
        }

        if to_score.is_empty() {
            continue;
        }

        // ── Step 2: parallel preview + score pass ─────────────────────────────────
        // No conn access here — pure I/O + pixel math over the pre-gathered regions.
        enum ScoreResult {
            Scored(f64, &'static str),
            /// A legacy score whose preview was never enlarged: keep it, stamp it.
            Kept,
            PreviewError(String),
        }

        let results: Vec<(i64, std::path::PathBuf, ScoreResult)> = to_score
            .par_iter()
            .map(|(photo_id, legacy, path, regions)| {
                let jpeg = match preview_fn(path) {
                    Ok(b) => b,
                    Err(e) => {
                        return (*photo_id, path.clone(), ScoreResult::PreviewError(e));
                    }
                };
                // A legacy score is measured again only when its preview was enlarged. The
                // preview tier is the decode at its own size up to 2048 px, so its header
                // says. A size that cannot be read decides nothing: the row stays as it is.
                if *legacy {
                    let dims = image::ImageReader::new(std::io::Cursor::new(&jpeg))
                        .with_guessed_format()
                        .ok()
                        .and_then(|r| r.into_dimensions().ok());
                    match dims {
                        None => {
                            let e = "preview size unreadable".to_string();
                            return (*photo_id, path.clone(), ScoreResult::PreviewError(e));
                        }
                        Some((w, h)) if !legacy_score_is_stale(w, h) => {
                            return (*photo_id, path.clone(), ScoreResult::Kept);
                        }
                        Some(_) => {}
                    }
                }
                let result = match score_fn(&jpeg, regions) {
                    Some((s, method)) => ScoreResult::Scored(s, method),
                    None => ScoreResult::PreviewError("image decode failed".to_string()),
                };
                (*photo_id, path.clone(), result)
            })
            .collect();

        // ── Step 3: sequential write pass ────────────────────────────────────────
        for (photo_id, _path, result) in results {
            match result {
                ScoreResult::PreviewError(e) => {
                    eprintln!("sharpness_index: preview/decode failed for photo {photo_id}: {e}");
                    outcome.failed += 1;
                    // Leave the row as it was (unscored, or its legacy score) so the next
                    // run retries.
                }
                ScoreResult::Scored(score, method) => {
                    write_sharpness(conn, photo_id, score, method)?;
                    done += 1;
                    emit_progress(SharpnessProgress { done: done + outcome.kept, total });
                }
                ScoreResult::Kept => {
                    keep_legacy_sharpness(conn, photo_id)?;
                    outcome.kept += 1;
                    emit_progress(SharpnessProgress { done: done + outcome.kept, total });
                }
            }

            if abort.load(Ordering::Relaxed) {
                outcome.aborted = true;
                break;
            }
        }

        if outcome.aborted {
            break;
        }
    }

    outcome.done = done;
    Ok(outcome)
}

/// Score JPEG bytes with the tiled sharpness scorer. Returns `None` when the image
/// cannot be decoded (unreadable / unsupported format). Used both by the indexer
/// and by the I7b analyzer hook.
///
/// Decoding is done here (not in `sharpness.rs`) because `sharpness.rs` is a pure
/// pixel-math function and does not import the `image` crate's JPEG decoder.
pub fn score_jpeg(jpeg: &[u8]) -> Option<f64> {
    let img = image::load_from_memory(jpeg).ok()?;
    Some(crate::sharpness::score_image(&img))
}

/// The per-photo region inputs the priority chain (H16c) chooses between: detected face
/// boxes and the camera AF point. Both are optional; whichever is present and non-empty
/// (faces first) decides the method. Fetched by the caller from the catalog (faces from
/// `faces__faces` under the `faces` feature; AF from `photo_metadata`), so this stays a
/// pure decision over already-gathered data — no catalog access, no feature gate.
#[derive(Debug, Clone, Default)]
pub struct RegionInputs {
    /// Detected face boxes on the oriented image (`faces__faces.bbox`). Empty when the
    /// `faces` feature is off or the photo has no faces.
    pub face_boxes: Vec<crate::sharpness_regions::NormBox>,
    /// Normalized AF point on the oriented image, parsed from the Sony `FocusLocation`
    /// makernote. `None` when the photo carries no usable AF point.
    pub af_point: Option<(f32, f32)>,
}

/// Score JPEG preview bytes with the region-aware priority chain (H16c):
///
/// 1. **face** — if any face box scores (non-degenerate, on-image), use the sharpest box.
/// 2. **afpoint** — else if an AF point is present, score its neighbourhood.
/// 3. **tile** — else the tiled top-percentile baseline.
///
/// Each earlier tier only wins when it actually produces a score; a face box entirely
/// off-image or an AF point that yields a degenerate patch falls through to the next tier,
/// so the method is honest about what was measured. Returns `None` only when the JPEG
/// cannot be decoded at all.
pub fn score_jpeg_regions(jpeg: &[u8], regions: &RegionInputs) -> Option<(f64, &'static str)> {
    let img = image::load_from_memory(jpeg).ok()?;
    Some(score_image_regions(&img, regions))
}

/// Apply the region-aware priority chain to an already-decoded image (the I7b analyzer
/// hook holds one, so it scores without re-decoding). Same tiers as [`score_jpeg_regions`].
pub fn score_image_regions(
    img: &image::DynamicImage,
    regions: &RegionInputs,
) -> (f64, &'static str) {
    use crate::sharpness_regions::{score_af_point, score_faces, Method, AF_PATCH_FRAC};
    let gray = img.to_luma8();

    // Tier 1: faces.
    if !regions.face_boxes.is_empty() {
        if let Some(s) = score_faces(&gray, &regions.face_boxes) {
            return (s, Method::Face.as_str());
        }
    }
    // Tier 2: AF point.
    if let Some((nx, ny)) = regions.af_point {
        if let Some(s) = score_af_point(&gray, nx, ny, AF_PATCH_FRAC) {
            return (s, Method::AfPoint.as_str());
        }
    }
    // Tier 3: tiled baseline.
    (crate::sharpness::score_gray(&gray), Method::Tile.as_str())
}

/// Read a photo's AF point from the catalog, parsed and oriented onto the preview frame.
///
/// The scan stored the raw Sony `FocusLocation` makernote and the EXIF orientation code as
/// `photo_metadata` entries (see `metadata::enrich_af_points`). This resolves both and hands
/// them to [`crate::sharpness_regions::parse_focus_location`], returning the normalized AF
/// point on the oriented image, or `None` when the photo has no usable AF data (non-Sony
/// file, older import before this field was captured, malformed value).
pub fn photo_af_point(conn: &Connection, photo_id: i64) -> Option<(f32, f32)> {
    use crate::metadata::{AF_ORIENTATION_KEY, AF_POINT_KEY};
    use rusqlite::OptionalExtension as _;

    let loc: Option<String> = conn
        .query_row(
            "SELECT value FROM photo_metadata WHERE photo_id = ?1 AND key = ?2 LIMIT 1",
            rusqlite::params![photo_id, AF_POINT_KEY],
            |r| r.get(0),
        )
        .optional()
        .ok()
        .flatten();
    let loc = loc?;

    let orientation: u16 = conn
        .query_row(
            "SELECT value FROM photo_metadata WHERE photo_id = ?1 AND key = ?2 LIMIT 1",
            rusqlite::params![photo_id, AF_ORIENTATION_KEY],
            |r| r.get::<_, String>(0),
        )
        .optional()
        .ok()
        .flatten()
        .and_then(|s| s.trim().parse().ok())
        .unwrap_or(1);

    crate::sharpness_regions::parse_focus_location(&loc, orientation)
}

/// The queue: every photo that is unscored or holds a legacy score (no
/// [`SHARPNESS_BASIS`]), as `(id, legacy)`, ordered by `id` for stable resumption.
fn load_queue(conn: &Connection) -> Result<Vec<(i64, bool)>, String> {
    let mut stmt = conn
        .prepare(
            "SELECT id, sharpness IS NOT NULL FROM photos
              WHERE sharpness IS NULL OR sharpness_basis IS NULL ORDER BY id ASC",
        )
        .map_err(|e| e.to_string())?;
    let rows = stmt
        .query_map([], |r| Ok((r.get::<_, i64>(0)?, r.get::<_, bool>(1)?)))
        .map_err(|e| e.to_string())?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| e.to_string())?;
    Ok(rows)
}

/// Write a sharpness score + method to the catalog for one photo, stamped with
/// [`SHARPNESS_BASIS`]. Caller holds the secondary catalog connection; there is no mutex
/// around this call.
pub fn write_sharpness(
    conn: &Connection,
    photo_id: i64,
    score: f64,
    method: &str,
) -> Result<(), String> {
    conn.execute(
        "UPDATE photos SET sharpness = ?1, sharpness_method = ?2, sharpness_basis = ?3 WHERE id = ?4",
        rusqlite::params![score, method, SHARPNESS_BASIS, photo_id],
    )
    .map_err(|e| e.to_string())?;
    Ok(())
}

/// Stamp a legacy score as current without changing it: its preview was never enlarged
/// ([`legacy_score_is_stale`] said no). Touches only a legacy score.
pub fn keep_legacy_sharpness(conn: &Connection, photo_id: i64) -> Result<(), String> {
    conn.execute(
        "UPDATE photos SET sharpness_basis = ?1
          WHERE id = ?2 AND sharpness IS NOT NULL AND sharpness_basis IS NULL",
        rusqlite::params![SHARPNESS_BASIS, photo_id],
    )
    .map_err(|e| e.to_string())?;
    Ok(())
}

/// A photo's region inputs (H16c) from the catalog: its face boxes (with the `faces`
/// feature) and its AF point.
pub fn photo_regions(conn: &Connection, photo_id: i64) -> RegionInputs {
    let af_point = photo_af_point(conn, photo_id);
    #[cfg(feature = "faces")]
    let face_boxes =
        crate::plugins::faces::store::face_boxes_for_photo(conn, photo_id).unwrap_or_default();
    #[cfg(not(feature = "faces"))]
    let face_boxes = Vec::new();
    RegionInputs { face_boxes, af_point }
}

/// What [`settle_from_decode`] did with one decode.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Settled {
    /// Scored (an unscored photo, or a stale legacy score measured again), and stamped.
    Scored,
    /// A legacy score whose decode is 2048 px or more: kept as it was, and stamped.
    Kept,
}

/// The decode hook's work for one preview-tier (or larger) decode of the file at `rel`
/// (catalog-root-relative, as `photos.path`): score the photo when it is unscored, and
/// settle a legacy score — measure it again when [`legacy_score_is_stale`] says the pre-#245
/// preview enlarged this decode, else keep and stamp it. A stamped score is never touched,
/// and neither is a path with no catalog row. `None` when there was nothing to do.
pub fn settle_from_decode(
    conn: &Connection,
    rel: &str,
    img: &image::DynamicImage,
) -> Result<Option<Settled>, String> {
    use rusqlite::OptionalExtension as _;
    let row: Option<(i64, bool)> = conn
        .query_row(
            "SELECT id, sharpness IS NOT NULL FROM photos
              WHERE path = ?1 AND (sharpness IS NULL OR sharpness_basis IS NULL)",
            rusqlite::params![rel],
            |r| Ok((r.get(0)?, r.get(1)?)),
        )
        .optional()
        .map_err(|e| e.to_string())?;
    let Some((id, legacy)) = row else { return Ok(None) };
    if legacy && !legacy_score_is_stale(img.width(), img.height()) {
        keep_legacy_sharpness(conn, id)?;
        return Ok(Some(Settled::Kept));
    }
    let (score, method) = score_image_regions(img, &photo_regions(conn, id));
    write_sharpness(conn, id, score, method)?;
    Ok(Some(Settled::Scored))
}

