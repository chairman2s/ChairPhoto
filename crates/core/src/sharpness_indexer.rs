    use crate::sharpness_regions::NormBox;
    use image::{GrayImage, Luma};

    /// Encode a grayscale image as JPEG bytes so `score_jpeg_regions` can decode it.
    fn jpeg_of(gray: &GrayImage) -> Vec<u8> {
        let dynimg = image::DynamicImage::ImageLuma8(gray.clone());
        let mut buf = std::io::Cursor::new(Vec::new());
        dynimg
            .write_to(&mut buf, image::ImageFormat::Jpeg)
            .unwrap();
        buf.into_inner()
    }

    fn sharp(w: u32, h: u32) -> GrayImage {
        GrayImage::from_fn(w, h, |x, y| {
            let on = ((x / 4) + (y / 4)) % 2 == 0;
            Luma([if on { 255u8 } else { 0u8 }])
        })
    }

